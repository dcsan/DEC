function htmlShell(js) {
  // Note: the bundled JS is appended verbatim. esbuild output never contains
  // a literal "</script>" sequence, so no escaping is needed here.
  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8" />
<meta name="viewport" content="width=device-width, initial-scale=1" />
<style>${CSS}</style>
</head>
<body>
<div id="root"><div class="empty">Loading…</div></div>
<script type="module">${js}</script>
</body>
</html>`;
}

function tsModule(exportName, html) {
  return (
    `// AUTO-GENERATED by scripts/build-widgets.mjs — do not edit by hand.\n` +
    `// Self-contained HTML (React bundled in) for an MCP App widget; served by\n` +
    `// src/mcp/server.ts as a UI resource. Regenerate with \`pnpm run build:widgets\`.\n` +
    `/* eslint-disable */\n` +
    `export const ${exportName} = ${JSON.stringify(html)};\n`
  );
}

for (const w of WIDGETS) {
  const result = await build({
    entryPoints: [w.entry],
    bundle: true,
    format: "esm",
    platform: "browser",
    target: "es2022",
    jsx: "automatic",
    minify: true,
    write: false,
    define: { "process.env.NODE_ENV": '"production"' },
    logLevel: "warning",
  });
  const js = result.outputFiles[0].text;
  const html = htmlShell(js);
  await writeFile(w.out, tsModule(w.exportName, html), "utf8");
  const kb = (Buffer.byteLength(html, "utf8") / 1024).toFixed(0);
  console.log(`built ${w.name} → ${w.out.split("/").slice(-1)[0]} (${kb} KB)`);
}
