// Build the MCP App widgets: bundle each React widget (React included) into one
// self-contained HTML file, then emit it as a TS string module the Worker can
// import. Run via `pnpm run build:widgets` (wired into the main build).
//
// Why a codegen step: the Cloudflare Worker has no filesystem at runtime, so the
// widget HTML must be a string baked into the Worker bundle. esbuild inlines
// React + the component into one IIFE; we drop that into an HTML shell and write
// it to src/mcp/widgets/<name>.generated.ts. Self-contained → empty CSP, no CDN.

import { build } from "esbuild";
import { writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const widgetsDir = resolve(here, "../src/mcp/widgets");

// Add a widget here to ship it. `entry` is bundled; `out` exports `cssVar`-named
// HTML; `cssVar` is the exported constant name the Worker imports.
const WIDGETS = [
  {
    name: "Decision Grid",
    entry: resolve(widgetsDir, "DecisionGridApp.tsx"),
    out: resolve(widgetsDir, "decisionGrid.generated.ts"),
    exportName: "DECISION_GRID_HTML",
  },
];

